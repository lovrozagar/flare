/**
 * Font generation pipeline — fetches Google Fonts CSS, parses it,
 * and generates registry.gen.ts, unicode-ranges.gen.ts, and per-font files.
 *
 * Usage: bun run scripts/populate-fonts.ts
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

function writeGenFile(filePath: string, body: string, generator: string): void {
	const normalized = body.replace(/\n*$/, "\n");
	const hash = createHash("sha256").update(normalized).digest("hex").slice(0, 12);
	const header = `/* @generated by ${generator} — do not edit. checksum: ${hash} */`;
	const fullContent = `${header}\n${normalized}`;

	if (existsSync(filePath)) {
		const existing = readFileSync(filePath, "utf-8");
		const firstLine = existing.split("\n")[0] ?? "";
		const match = firstLine.match(/checksum: ([0-9a-f]{12})/);
		if (match?.[1] === hash) return;
	}

	mkdirSync(join(filePath, ".."), { recursive: true });
	writeFileSync(filePath, fullContent, "utf-8");
}

