/* ── fallback font for category ────────────────────────────────── */

const CATEGORY_FALLBACK: Record<string, string> = {
	display: "Arial",
	handwriting: "Arial",
	monospace: "Courier New",
	"sans-serif": "Arial",
	serif: "Times New Roman",
};

/* ── capsizecss metrics loader ─────────────────────────────────── */

/* @capsizecss/metrics provides pre-calculated metrics for many fonts */
async function getFallbackMetrics(
	family: string,
	category: string,
): Promise<
	| {
			ascentOverride: string;
			descentOverride: string;
			fallbackFont: string;
			lineGapOverride: string;
			sizeAdjust: string;
	  }
	| undefined
> {
	const noSpaces = family.replace(/ /g, "");
	const slug = noSpaces[0].toLowerCase() + noSpaces.slice(1);
	try {
		const mod = await import(`@capsizecss/metrics/${slug}`);
		const metrics = mod.default ?? mod;

		const fallbackFont = CATEGORY_FALLBACK[category] ?? "Arial";
		let fallbackMetrics: {
			ascent: number;
			capHeight: number;
			descent: number;
			lineGap: number;
			unitsPerEm: number;
		};

		try {
			const fbNoSpaces = fallbackFont.replace(/ /g, "");
			const fallbackSlug = fbNoSpaces[0].toLowerCase() + fbNoSpaces.slice(1);
			const fallbackMod = await import(`@capsizecss/metrics/${fallbackSlug}`);
			fallbackMetrics = fallbackMod.default ?? fallbackMod;
		} catch {
			return undefined;
		}

		/* calculate size-adjust and override values */
		const sizeAdjust =
			((metrics.unitsPerEm / fallbackMetrics.unitsPerEm) *
				(fallbackMetrics.ascent - fallbackMetrics.descent + fallbackMetrics.lineGap)) /
			(metrics.ascent - metrics.descent + metrics.lineGap);

		const ascentOverride = metrics.ascent / (metrics.unitsPerEm * sizeAdjust);
		const descentOverride = Math.abs(metrics.descent) / (metrics.unitsPerEm * sizeAdjust);
		const lineGapOverride = metrics.lineGap / (metrics.unitsPerEm * sizeAdjust);

		return {
			ascentOverride: `${(ascentOverride * 100).toFixed(2)}%`,
			descentOverride: `${(descentOverride * 100).toFixed(2)}%`,
			fallbackFont,
			lineGapOverride: `${(lineGapOverride * 100).toFixed(2)}%`,
			sizeAdjust: `${(sizeAdjust * 100).toFixed(2)}%`,
		};
	} catch {
		return undefined;
	}
}

/* ── Google Fonts CSS parser ───────────────────────────────────── */

interface ParsedEntry {
	family: string;
	style: "italic" | "normal";
	subset: string;
	unicodeRange: string;
	url: string;
	weight: string;
}

function parseCss(css: string, family: string): ParsedEntry[] {
	const entries: ParsedEntry[] = [];

	/* match each @font-face block, preceded by a subset comment */
	const blockRe = /\/\*\s*([a-zA-Z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
	let match: RegExpExecArray | null;

	while ((match = blockRe.exec(css)) !== null) {
		const subset = match[1] ?? "";
		const body = match[2] ?? "";

		const styleMatch = /font-style:\s*(italic|normal)/.exec(body);
		const weightMatch = /font-weight:\s*([\d\s]+)/.exec(body);
		const srcMatch = /url\(([^)]+)\)\s*format\(['"]woff2['"]\)/.exec(body);
		const rangeMatch = /unicode-range:\s*([^;]+)/.exec(body);

		if (srcMatch && rangeMatch) {
			entries.push({
				family,
				style: (styleMatch?.[1] as "italic" | "normal") ?? "normal",
				subset,
				unicodeRange: rangeMatch[1]?.trim() ?? "",
				url: srcMatch[1]?.trim() ?? "",
				weight: weightMatch?.[1]?.trim() ?? "400",
			});
		}
	}

	return entries;
}

async function fetchGoogleFontCss(family: string, variable: boolean): Promise<string | undefined> {
	const encodedFamily = family.replace(/\s+/g, "+");
	const spec = variable
		? `${encodedFamily}:ital,wght@0,100..900;1,100..900`
		: `${encodedFamily}:ital,wght@0,400;0,700;1,400;1,700`;

	const url = `https://fonts.googleapis.com/css2?family=${spec}&display=swap`;

	/* woff2 user-agent trick */
	const res = await fetch(url, {
		headers: {
			"User-Agent":
				"Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
		},
	});

	if (!res.ok) return undefined;
	return res.text();
}

/* ── slug helpers ──────────────────────────────────────────────── */

function toSlug(family: string): string {
	return family.toLowerCase().replace(/\s+/g, "-");
}

function toCamelCase(family: string): string {
	return family
		.replace(/[^a-zA-Z0-9\s]/g, "")
		.split(/\s+/)
		.map((word, i) => {
			const lower = word.toLowerCase();
			if (i === 0) return lower;
			return lower[0]?.toUpperCase() + lower.slice(1);
		})
		.join("");
}

/* ── output generation ─────────────────────────────────────────── */

interface FontGenData {
	camelName: string;
	category: string;
	fallbackMetrics?: {
		ascentOverride: string;
		descentOverride: string;
		fallbackFont: string;
		lineGapOverride: string;
		sizeAdjust: string;
	};
	family: string;
	slug: string;
	subsetEntries: Array<{
		style: "italic" | "normal";
		subset: string;
		unicodeRange: string;
		weight: string;
	}>;
	subsets: string[];
	weights: number[] | string;
}

function generatePerFontFile(font: FontGenData): string {
	const subsetsType = font.subsets.map((s) => `"${s}"`).join(" | ");
	const slug = font.slug;

	const entriesStr = font.subsetEntries
		.map(
			(e) =>
				`    { style: "${e.style}", subset: "${e.subset}", ` +
				`unicodeRange: "${e.unicodeRange}", ` +
				`url: "/fonts/${slug}/${buildFileName(e)}", ` +
				`weight: ${JSON.stringify(e.weight)} }`,
		)
		.join(",\n");

	const metricsStr = font.fallbackMetrics
		? `  fallbackMetrics: ${JSON.stringify(font.fallbackMetrics, null, 4).replace(/\n/g, "\n  ")},\n`
		: "";

	const weightsStr = typeof font.weights === "string" ? `"${font.weights}"` : JSON.stringify(font.weights);

	return `import { createRegistryFont } from "./create-registry-font"
import type { Font } from "./types"

export const ${font.camelName}: Font<${subsetsType}> = createRegistryFont({
  category: "${font.category}",
${metricsStr}  family: "${font.family}",
  subsetEntries: [
${entriesStr},
  ],
  subsets: [${font.subsets.map((s) => `"${s}"`).join(", ")}],
  weights: ${weightsStr},
})
`;
}

function buildFileName(entry: { style: "italic" | "normal"; subset: string; weight: string }): string {
	const parts = [entry.subset];
	if (entry.style === "italic") parts.push("i");

	/* static weight: append weight number */
	if (/^\d+$/.test(entry.weight)) {
		parts.push(entry.weight);
	}

	return `${parts.join("-")}.woff2`;
}

/* ── main pipeline ─────────────────────────────────────────────── */

async function main(): Promise<void> {
	const fontsDir = join(import.meta.dirname ?? ".", "..", "src", "fonts");

	if (!existsSync(fontsDir)) {
		mkdirSync(fontsDir, { recursive: true });
	}

	const allFonts: FontGenData[] = [];
	const errors: string[] = [];

	for (const family of FONTS) {
		process.stdout.write(`Processing ${family}... `);

		/* try variable first, fall back to static */
		let css = await fetchGoogleFontCss(family, true);
		let isVariable = true;

		if (!css || css.trim().length < 50) {
			css = await fetchGoogleFontCss(family, false);
			isVariable = false;
		}

		if (!css) {
			errors.push(family);
			console.log("FAILED (no CSS)");
			continue;
		}

		const entries = parseCss(css, family);
		if (entries.length === 0) {
			errors.push(family);
			console.log("FAILED (no entries parsed)");
			continue;
		}

		/* determine subsets + weights */
		const subsets = [...new Set(entries.map((e) => e.subset))].sort();

		let weights: number[] | string;
		if (isVariable) {
			/* use the range from the first entry */
			const first = entries[0];
			weights = first?.weight ?? "100 900";
		} else {
			weights = [...new Set(entries.map((e) => Number.parseInt(e.weight, 10)))].sort((a, b) => a - b);
		}

		/* deduplicate subset entries (same subset + style + weight = one entry) */
		const seen = new Set<string>();
		const deduped = entries.filter((e) => {
			const key = `${e.subset}:${e.style}:${e.weight}`;
			if (seen.has(key)) return false;
			seen.add(key);
			return true;
		});

		const category = CATEGORY_MAP[family] ?? "sans-serif";
		const fallbackMetrics = await getFallbackMetrics(family, category);

		const fontData: FontGenData = {
			camelName: toCamelCase(family),
			category,
			fallbackMetrics,
			family,
			slug: toSlug(family),
			subsetEntries: deduped.map((e) => ({
				style: e.style,
				subset: e.subset,
				unicodeRange: e.unicodeRange,
				weight: e.weight,
			})),
			subsets,
			weights,
		};

		allFonts.push(fontData);
		console.log(`OK (${subsets.length} subsets, ${deduped.length} entries)`);
	}

	/* generate per-font files */
	for (const font of allFonts) {
		const content = generatePerFontFile(font);
		writeFileSync(join(fontsDir, `${font.slug}.ts`), content);
	}

	/* generate registry.gen.ts */
	const registryEntries = allFonts
		.map((f) => `  ["${f.family}", "${f.slug}", "${f.camelName}", "${f.category}"]`)
		.join(",\n");

	writeGenFile(
		join(fontsDir, "registry.gen.ts"),
		`\nexport const FONT_REGISTRY: Array<[family: string, slug: string, camelName: string, category: string]> = [\n${registryEntries},\n]\n`,
		"flare/fonts",
	);

	/* generate unicode-ranges.gen.ts */
	const allRanges = new Map<string, string>();
	for (const font of allFonts) {
		for (const entry of font.subsetEntries) {
			if (!allRanges.has(entry.subset)) {
				allRanges.set(entry.subset, entry.unicodeRange);
			}
		}
	}

	const rangeEntries = [...allRanges.entries()]
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([subset, range]) => `  "${subset}": "${range}"`)
		.join(",\n");

	writeGenFile(
		join(fontsDir, "unicode-ranges.gen.ts"),
		`\nexport const UNICODE_RANGES: Record<string, string> = {\n${rangeEntries},\n}\n`,
		"flare/fonts",
	);

	/* summary */
	console.log(`\nGenerated ${allFonts.length} fonts`);
	if (errors.length > 0) {
		console.log(`Failed: ${errors.join(", ")}`);
	}
}

main().catch(console.error);
