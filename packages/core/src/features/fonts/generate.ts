import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RegistryFontData } from "./shared/create-font.ts";

// `registry.json`: one family per key. The key is the `@lovrozagar/flare/fonts/<id>` path (B78).
export type FontRegistryFile = Record<string, RegistryFontData>;

export type GeneratedFont = { fileName: string; text: string };

const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;

// The family's metadata as a JSON literal. `<` is written as an escape, so no generated module holds a raw `</style>`
// or `<script>`, and registryFont still receives the name as the registry wrote it.
function literal(data: RegistryFontData): string {
	return JSON.stringify(data, null, "\t").replaceAll("<", "\\u003C");
}

function moduleText(data: RegistryFontData): string {
	return (
		"// Generated by features/fonts/generate.ts from registry.json. Do not edit.\n" +
		'import { registryFont, type Font } from "../create-font.ts";\n\n' +
		`const font: Font = /* @__PURE__ */ registryFont(${literal(data)});\n\nexport default font;\n`
	);
}

// One module per key, in key order, and no barrel (B78).
export function generateFonts(registry: FontRegistryFile): GeneratedFont[] {
	return Object.entries(registry)
		.toSorted(([left], [right]) => (left < right ? -1 : 1))
		.map(([id, data]) => {
			if (!ID.test(id)) throw new Error(`font id ${JSON.stringify(id)} is not lowercase words joined by hyphens`);
			return { fileName: `${id}.ts`, text: moduleText(data) };
		});
}

// `bun run fonts:generate`: replaces `shared/generated/` under the package root with the registry's modules.
export function writeFonts(root: string): void {
	const fonts = join(root, "src/features/fonts");
	const registry: FontRegistryFile = JSON.parse(readFileSync(join(fonts, "registry.json"), "utf8"));
	const out = join(fonts, "shared/generated");
	rmSync(out, { recursive: true, force: true });
	mkdirSync(out, { recursive: true });
	for (const module of generateFonts(registry)) writeFileSync(join(out, module.fileName), module.text);
}
