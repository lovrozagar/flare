import { posix } from "path";
import { assignIds, extractServerFns, fnId, type FnSite } from "../route-meta/index.ts";
import { escapeSource } from "./escape.ts";

// Where the file is written, under the app root (dx/plugin.md).
const OUT_DIR = "src/_gen";

// src/_gen/server-fns.gen.ts: every exported createServerFn as a lazy import keyed by its B41 id. The app passes
// `serverFns` to createServer (dx/server.md). `files` are root-relative. A call that is not a direct export, and two
// ids that collide, fail the build.
export function generateServerFns(
	files: readonly string[],
	read: (file: string) => string,
	hash: (path: string, name: string) => string = fnId,
): { source: string; ids: Map<string, FnSite> } {
	// A generated file is not app code, so every listed file sits outside OUT_DIR and its import starts with `../`.
	const sites = files
		.filter((file) => !file.startsWith(`${OUT_DIR}/`))
		.sort()
		.flatMap((file) => extractServerFns(file, read(file)).map((record) => ({ path: file, name: record.name })));
	const ids = assignIds(sites, hash);
	const entries = [...ids].map(([id, site]) => {
		const from = escapeSource(posix.relative(OUT_DIR, site.path));
		return `\t"${escapeSource(id)}": () => import("${from}").then((loaded) => loaded.${site.name}),`;
	});
	const body = entries.length === 0 ? "{}" : `{\n${entries.join("\n")}\n}`;
	return { source: `// Generated by flare. Do not edit.\nexport const serverFns = ${body};\n`, ids };
}
