import { expect, it } from "vitest"
import { fnId } from "../route-meta/index.ts"
import { generateServerFns } from "./server-fns.ts"

const FN = 'import { createServerFn } from "@lovrozagar/flare/server-fn";\n'

const sources: Record<string, string> = {
	"src/fns/echo.ts": `${FN}export const echo = createServerFn().handler(h);\nexport const shout = createServerFn().handler(h);\n`,
	"src/routes/_root_/about/about.page.tsx":
		'import { createPage } from "@lovrozagar/flare";\nexport const route = createPage("_root_/about").render(r);\n',
	"src/lib/name.ts": `${FN}export const echo = createServerFn({ method: "get" }).handler(h);\n`,
	"src/_gen/server-fns.gen.ts": "export const serverFns = {};\n",
}

function read(file: string): string {
	return sources[file]
}

it("lazy import", () => {
	const generated = generateServerFns(Object.keys(sources), read)
	expect(generated.source).toBe(
		[
			"// Generated by flare. Do not edit.",
			"export const serverFns = {",
			`\t"${fnId("src/fns/echo.ts", "echo")}": () => import("../fns/echo.ts").then((loaded) => loaded.echo),`,
			`\t"${fnId("src/fns/echo.ts", "shout")}": () => import("../fns/echo.ts").then((loaded) => loaded.shout),`,
			`\t"${fnId("src/lib/name.ts", "echo")}": () => import("../lib/name.ts").then((loaded) => loaded.echo),`,
			"};",
			"",
		].join("\n"),
	)
	// The same export name in two files is two functions.
	expect(generated.ids.size).toBe(3)
})

it("no fns", () => {
	expect(generateServerFns([], read).source).toBe("// Generated by flare. Do not edit.\nexport const serverFns = {};\n")
})

it("collision", () => {
	expect(() => generateServerFns(["src/fns/echo.ts"], read, () => "0000000000000000")).toThrow(
		"Server function ids collide: src/fns/echo.ts echo and src/fns/echo.ts shout",
	)
})

it("not exported", () => {
	const loose: Record<string, string> = {
		"src/fns/loose.ts": `${FN}const echo = createServerFn().handler(h);\nexport { echo };\n`,
	}
	expect(() => generateServerFns(["src/fns/loose.ts"], (file) => loose[file])).toThrow(/must be a direct export/)
})
