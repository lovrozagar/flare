import { posix } from "node:path"
import { parseSync } from "oxc-parser"
import { escapeSource } from "./escape.ts"
import { generateRoutes } from "./routes.ts"
import { scanRoute, type Scan } from "./scan.ts"

const OUT_DIR = "src/_gen"
const QUERY = "@lovrozagar/flare/query"
const SEGMENT = ".segment.ts"

// `routeFiles` are relative to `routesDir`. `appFiles` and `read` are root-relative.
export type TypesInput = {
	routeFiles: readonly string[]
	appFiles: readonly string[]
	read: (file: string) => string
	routesDir?: string
}

type Module = { id: string; file: string; scan: Scan; type: string }

type Entries = ReadonlyArray<readonly [string, string]>

// src/_gen/types.gen.d.ts augments `FlareRegister` (dx/types.md). Every value names a type through
// `typeof import("<file>").route`, so no type is derived from text. It never sets `auth`, `env`, or
// `serverContext`, and names no virtual module. `parents` and `modules` are returned for the checks that read them.
export function generateTypes(input: TypesInput): {
	source: string
	parents: Record<string, string[]>
	modules: string[]
} {
	const routesDir = input.routesDir ?? "src/routes"
	const path = (file: string): string => `${routesDir}/${file}`
	const generated = generateRoutes(input.routeFiles, (file) => input.read(path(file)), { routesDir })
	// generateRoutes lists a segment with the layouts, since it joins the chain (BUGS.md B22).
	const modules: Module[] = [...generated.layouts, ...generated.routes]
		.map((item) => ({
			id: item.id,
			file: item.file,
			scan: scanRoute(path(item.file), input.read(path(item.file))),
			type: `typeof import("${escapeSource(posix.relative(OUT_DIR, path(item.file)))}").route`,
		}))
		.sort((left, right) => (left.id < right.id ? -1 : 1))
	const layouts = generated.layouts.filter((layout) => !layout.file.endsWith(SEGMENT)).map((layout) => layout.id)
	const parents: Record<string, string[]> = {}
	for (const module of modules) parents[module.id] = parentsOf(module.id, layouts)
	const fields = [
		map("routes", pageUrls(generated.routes)),
		pageIds(generated.routes.map((route) => route.id)),
		map(
			"routeModules",
			modules.map((module) => [module.id, module.type]),
		),
		map(
			"routeParents",
			modules.map((module) => [module.id, tuple(parentsOf(module.id, layouts))]),
		),
		optional("authModes", authModes(modules)),
		optional("routeSearchParams", outputs(modules, "search")),
		optional("routeParams", outputs(modules, "params")),
		input.appFiles.some((file) => importsQuery(file, input.read(file))) ? "\t\thasQueryClient: true;" : "",
	].filter((field) => field !== "")
	const register = `declare module "@lovrozagar/flare" {\n\tinterface FlareRegister {\n${fields.join("\n")}\n\t}\n}\n`
	const source = `// Generated by flare. Do not edit.\nexport {};\n\n${register}`
	return { source, parents, modules: modules.map((module) => module.id) }
}

// Layout and root ids that hold `id`, outside-in. A segment and a group without a layout file are never parents.
function parentsOf(id: string, layouts: readonly string[]): string[] {
	return layouts
		.filter((layout) => layout !== id && id.startsWith(`${layout}/`))
		.sort((left, right) => left.length - right.length)
}

// A page that renders, keyed by its URL pattern, with its bracket params. A `.response()` page has no entry.
function pageUrls(routes: ReturnType<typeof generateRoutes>["routes"]): Entries {
	return routes
		.filter((route) => !route.response)
		.map((route) => {
			const params = Object.entries(route.params).map(([name, type]) => `${name}: ${type}`)
			return [route.path, `{ params: ${params.length === 0 ? "{}" : `{ ${params.join("; ")} }`} }`]
		})
}

// Every page id as a plain union, so a page target (`Link`, `navigate`, `redirect`) is known without reading a route
// module's type. A loader that throws `redirect()` then infers its own return type without a loop through its own
// module (BUGS.md 105).
function pageIds(ids: readonly string[]): string {
	const union = ids.toSorted().map((id) => `"${escapeSource(id)}"`)
	return `\t\tpageIds: ${union.length === 0 ? "never" : union.join(" | ")};`
}

function authModes(modules: readonly Module[]): Entries {
	return modules.flatMap((module) => {
		const auth = module.scan.auth
		return auth === undefined ? [] : [[module.id, auth === true ? "true" : '"optional"'] as const]
	})
}

// Each file's own `.input()` output, keyed by its route id. A parent's output stays on the parent.
function outputs(modules: readonly Module[], side: "search" | "params"): Entries {
	const helper = side === "search" ? "SearchOutput" : "ParamsOutput"
	return modules
		.filter((module) => module.scan.input[side])
		.map((module) => [module.id, `import("@lovrozagar/flare").${helper}<${module.type}>`] as const)
}

function map(name: string, entries: Entries): string {
	const lines = entries.map(([key, value]) => `\t\t\t"${escapeSource(key)}": ${value};`)
	return lines.length === 0 ? `\t\t${name}: {};` : `\t\t${name}: {\n${lines.join("\n")}\n\t\t};`
}

// A field with no entry is left out, so an app that sets no auth has no `authModes` (dx/types.md).
function optional(name: string, entries: Entries): string {
	return entries.length === 0 ? "" : map(name, entries)
}

function tuple(ids: readonly string[]): string {
	return `[${ids.map((id) => `"${escapeSource(id)}"`).join(", ")}]`
}

// The import counts, not the text: a comment or a string that names the package does not (dx/types.md).
function importsQuery(file: string, source: string): boolean {
	const parsed = parseSync(file, source, { sourceType: "module", lang: "tsx" })
	const [error] = parsed.errors
	if (error !== undefined) throw new Error(`${file}: ${error.message}`)
	return parsed.program.body.some(
		(statement) => statement.type === "ImportDeclaration" && statement.source.value === QUERY,
	)
}
